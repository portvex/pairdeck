# Homebrew formula template for pairdeck.
#
# To publish a release:
#   1. Push a tag `vX.Y.Z`; the Release workflow uploads the tarballs and
#      sha256sums.txt to the GitHub release.
#   2. Replace OWNER/REPO with the GitHub repository, set `version`, and copy
#      the matching sha256 values from sha256sums.txt below.
#   3. Put this file in a tap repository (e.g. OWNER/homebrew-tap, path
#      Formula/pairdeck.rb); users then run `brew install OWNER/tap/pairdeck`.
class Pairdeck < Formula
  desc "Modern twin-panel terminal file manager in the spirit of Midnight Commander"
  homepage "https://github.com/OWNER/REPO"
  version "0.1.0"
  license "MIT"

  on_macos do
    # Universal binary: runs on Apple silicon and Intel.
    url "https://github.com/OWNER/REPO/releases/download/v#{version}/pairdeck-v#{version}-universal-apple-darwin.tar.gz"
    sha256 "REPLACE_WITH_SHA256_OF_universal-apple-darwin.tar.gz"
  end

  on_linux do
    on_intel do
      url "https://github.com/OWNER/REPO/releases/download/v#{version}/pairdeck-v#{version}-x86_64-unknown-linux-musl.tar.gz"
      sha256 "REPLACE_WITH_SHA256_OF_x86_64-unknown-linux-musl.tar.gz"
    end
    on_arm do
      url "https://github.com/OWNER/REPO/releases/download/v#{version}/pairdeck-v#{version}-aarch64-unknown-linux-musl.tar.gz"
      sha256 "REPLACE_WITH_SHA256_OF_aarch64-unknown-linux-musl.tar.gz"
    end
  end

  def install
    bin.install "pdeck"
    doc.install "README.md"
    # Man page and completions are generated by the binary itself.
    (man1/"pdeck.1").write Utils.safe_popen_read(bin/"pdeck", "--man")
    generate_completions_from_executable(bin/"pdeck", "--completions")
  end

  def caveats
    <<~EOS
      pairdeck's binary is `pdeck`. For "cd to the last directory on exit", add to your shell rc:
        pdcd() { local f=$(mktemp); pdeck -P "$f" "$@"; cd "$(cat "$f")"; rm -f "$f"; }
      Icons need a Nerd Font in your terminal (or set nerd_fonts = false).
    EOS
  end

  test do
    assert_match "pairdeck", shell_output("#{bin}/pdeck --version")
    assert_match ".TH PDECK 1", shell_output("#{bin}/pdeck --man")
    assert_match "_pdeck", shell_output("#{bin}/pdeck --completions bash")
  end
end
